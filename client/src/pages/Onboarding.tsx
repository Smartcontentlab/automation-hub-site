import AppLayout from "@/components/AppLayout";
import GeneratorOutput from "@/components/GeneratorOutput";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { trpc } from "@/lib/trpc";
import { ClipboardList, Download, Loader2, Sparkles } from "lucide-react";
import { useState } from "react";
import { toast } from "sonner";

const NICHES = ["Dental Office", "Real Estate Agent", "Plumber", "HVAC Company", "Med Spa", "Law Firm", "Auto Repair Shop", "Gym / Fitness Studio"];

function markdownToHtml(md: string): string {
  return md
    .replace(/^## (.+)$/gm, "<h2>$1</h2>")
    .replace(/^### (.+)$/gm, "<h3>$1</h3>")
    .replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")
    .replace(/^\| (.+) \|$/gm, (_, row) => `<tr>${row.split(" | ").map((c: string) => `<td>${c}</td>`).join("")}</tr>`)
    .replace(/^- \[x\] (.+)$/gm, "<li class='done'>✅ $1</li>")
    .replace(/^- \[ \] (.+)$/gm, "<li class='todo'>☐ $1</li>")
    .replace(/^- (.+)$/gm, "<li>$1</li>")
    .replace(/((<li[^>]*>.*<\/li>\n?)+)/g, "<ul>$1</ul>");
}

