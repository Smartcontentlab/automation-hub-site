export default function Onboarding() {
  const [form, setForm] = useState({ businessName: "", niche: "" });
  const [output, setOutput] = useState<string | null>(null);

  const mutation = trpc.generate.onboardingChecklist.useMutation({
    onSuccess: (data) => { setOutput(data.content); toast.success("Onboarding checklist generated!"); },
    onError: (err) => toast.error(err.message || "Generation failed."),
  });

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (!form.businessName || !form.niche) { toast.error("Please fill in all fields."); return; }
    mutation.mutate(form);
  };

  return (
    <AppLayout>
      <div className="p-6 lg:p-10 max-w-3xl mx-auto">
        <div className="flex items-center gap-3 mb-6">
          <div className="w-9 h-9 rounded-xl bg-primary/10 border border-primary/20 flex items-center justify-center">
            <ClipboardList className="w-5 h-5 text-primary" />
          </div>
          <div>
            <h1 className="font-display text-xl font-semibold tracking-tight text-foreground">Client Onboarding Checklist</h1>
            <p className="text-xs text-muted-foreground">Generate a step-by-step onboarding document for a new chatbot client.</p>
          </div>
        </div>

        <form onSubmit={handleSubmit} className="rounded-2xl border border-border bg-card p-6 space-y-5 mb-6">
          <div className="space-y-1.5">
            <Label htmlFor="businessName" className="text-sm font-medium text-foreground">Client Business Name</Label>
            <Input id="businessName" placeholder="e.g. Bright Smile Dental" value={form.businessName}
              onChange={e => setForm(f => ({ ...f, businessName: e.target.value }))} />
          </div>
          <div className="space-y-1.5">
            <Label htmlFor="niche" className="text-sm font-medium text-foreground">Business Niche</Label>
            <Input id="niche" placeholder="e.g. Dental Office" value={form.niche}
              onChange={e => setForm(f => ({ ...f, niche: e.target.value }))} />
            <div className="flex flex-wrap gap-1.5 pt-1">
              {NICHES.map(n => (
                <button key={n} type="button" onClick={() => setForm(f => ({ ...f, niche: n }))}
                  className={`px-2.5 py-1 rounded-full text-xs border transition-colors ${
                    form.niche === n
                      ? "bg-primary/15 border-primary/40 text-primary"
                      : "border-border text-muted-foreground hover:border-primary/30 hover:text-foreground"
                  }`}>
                  {n}
                </button>
              ))}
            </div>
          </div>
          <Button type="submit" disabled={mutation.isPending} className="w-full gap-2">
            {mutation.isPending ? <><Loader2 className="w-4 h-4 animate-spin" /> Generating...</> : <><Sparkles className="w-4 h-4" /> Generate Onboarding Checklist</>}
          </Button>
        </form>

        {mutation.isPending && (
          <div className="rounded-2xl border border-border bg-card p-8 flex flex-col items-center gap-3 text-center">
            <Loader2 className="w-6 h-6 text-primary animate-spin" />
            <p className="text-sm text-muted-foreground">AI is building your onboarding checklist...</p>
            <p className="text-xs text-muted-foreground">This may take 10–15 seconds.</p>
          </div>
        )}

        {!mutation.isPending && !output && (
          <div className="rounded-2xl border border-dashed border-border p-10 text-center">
            <ClipboardList className="w-6 h-6 text-muted-foreground/50 mx-auto mb-3" />
            <p className="text-sm text-foreground font-medium mb-1">No checklist yet</p>
            <p className="text-xs text-muted-foreground max-w-xs mx-auto">
              Enter a client name and niche above to generate a phased onboarding checklist.
            </p>
          </div>
        )}

        {output && !mutation.isPending && (
          <div className="space-y-3">
            <div className="flex justify-end">
              <Button variant="outline" size="sm"
                onClick={() => exportChecklistPdf(output, form.businessName, form.niche)}
                className="gap-2 text-xs">
                <Download className="w-3.5 h-3.5" /> Export as PDF
              </Button>
            </div>
            <GeneratorOutput content={output} label="Client Onboarding Checklist" />
          </div>
        )}
      </div>
    </AppLayout>
  );
}
